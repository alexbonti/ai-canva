import { chromium } from "/Users/alessiobonti/dev/ai-canva/client/node_modules/playwright-core/index.mjs";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error") errs.push("console: " + m.text().slice(0, 400)); });
await page.goto("http://127.0.0.1:5183", { waitUntil: "load" });
await page.waitForTimeout(3000);
console.log("has __dsh:", await page.evaluate(() => !!window.__dsh));
console.log("body text:", (await page.evaluate(() => document.body.innerText)).slice(0, 300).replace(/\n/g, " | "));
console.log(errs.slice(0, 6).join("\n---\n"));
await browser.close();
