interface IconProps {
  name: IconName | string;
  /** Rendered size in px (default 16). */
  size?: number;
  /** Stroke width (default 1.75 — the app's one weight). */
  stroke?: number;
  className?: string;
  /** Accessible label; omit for decorative icons. */
  title?: string;
}

/** One icon, one stroke weight, one box. Renders nothing unknown is impossible. */
function IconInner({ name, size = 16, stroke = 1.75, className = "", title }: IconProps) {
  const raw = (PATHS as Record<string, string>)[name];
  if (!raw) return null;
  // The authored path strings separate shapes with a space, which would become a
  // whitespace text node inside the <svg> — and textContent (which the E2E suite
  // matches button labels with) would pick those spaces up. Keep the markup clean.
  const inner = raw.replace(/>\s+</g, "><");
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={"flex-shrink-0 " + className}
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      <g dangerouslySetInnerHTML={{ __html: inner }} />
    </svg>
  );
}

