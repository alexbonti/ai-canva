// Ollama Cloud integration for AI text generation (Firebase Cloud Functions).
//
// Ollama Cloud runs models remotely and exposes a standard Ollama HTTP API at
// https://ollama.com. See https://docs.ollama.com/cloud for details. This uses
// the native /api/chat endpoint (non-streaming), so it also works against a
// local Ollama daemon by setting OLLAMA_HOST.

interface ChatMessage {
  role: string;
  content: string;
}

interface ChatResponse {
  model?: string;
  message?: { role?: string; content?: string };
  error?: string;
  /** Input tokens sent to the model (Ollama non-streaming response). */
  prompt_eval_count?: number;
  /** Output tokens generated by the model. */
  eval_count?: number;
  /** Why generation stopped: "stop" (natural), "length" (hit the output cap). */
  done_reason?: string;
  /** Streaming chunk marker: the final chunk carries done:true + the counters. */
  done?: boolean;
}

/** Structured result of a text generation call, including token usage. */
export interface GenerateResult {
  content: string;
  model: string;
  promptTokens: number;
  completionTokens: number;
  totalTokens: number;
  /**
   * True when the model ran out of output budget before finishing. The client
   * must NOT treat a truncated reply as a complete artifact (JSX gets cut
   * mid-expression), it should ask for a retry/simpler prompt instead.
   */
  truncated: boolean;
}

/** Output token budget per call — also the truncation threshold. */
const NUM_PREDICT = 32_768;

/**
 * Calls an Ollama model with a system + user prompt and returns the text reply
 * plus token usage.
 *
 * - Endpoint:  POST {OLLAMA_HOST}/api/chat   (default https://ollama.com)
 * - Auth:      Bearer token from OLLAMA_API_KEY
 * - Model:     OLLAMA_MODEL (default "deepseek-v4.1-flash:1017")
 */
export interface GenerateOptions {
  /**
   * Provider reasoning toggle. `false` turns the model's "thinking" off — for a
   * straightforward page build that is both faster and cheaper (thinking tokens
   * are counted in `eval_count` but never shown). Omitted = provider default.
   */
  think?: boolean;
}

export async function generateContent(
  systemPrompt: string,
  userPrompt: string,
  opts: GenerateOptions = {}
): Promise<GenerateResult> {
  const host = process.env.OLLAMA_HOST || "https://ollama.com";
  const apiKey = process.env.OLLAMA_API_KEY;
  const model = process.env.OLLAMA_MODEL || "deepseek-v4.1-flash:1017";

  const headers: Record<string, string> = { "Content-Type": "application/json" };
  if (apiKey) {
    headers.Authorization = `Bearer ${apiKey}`;
  }

  const messages: ChatMessage[] = [
    { role: "system", content: systemPrompt },
    { role: "user", content: userPrompt },
  ];

  // STREAM the reply as NDJSON. A non-streamed long generation dies at ~60s
  // ("fetch failed" / remote end closed) because nothing keeps the connection
  // alive — exactly what happens for 8-30k-token UI/Code replies. Streaming
  // keeps the socket active and still enforces one 300s deadline for the whole
  // generation.
  const res = await fetch(`${host}/api/chat`, {
    method: "POST",
    headers,
    signal: AbortSignal.timeout(300_000),
    body: JSON.stringify({
      model,
      stream: true,
      // `think` only when explicitly set: undefined fields would be dropped by
      // JSON.stringify anyway, but being explicit keeps the provider default.
      ...(opts.think === undefined ? {} : { think: opts.think }),
      options: { num_predict: NUM_PREDICT },
      messages,
    }),
  });

  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new Error(
      `Ollama request failed (${res.status}): ${text.slice(0, 300)}`
    );
  }
  if (!res.body) {
    throw new Error("Ollama returned no response body.");
  }

  // Ollama sends one JSON object per line; the last one carries done:true plus
  // the token counters and the stop reason.
  let content = "";
  let meta: ChatResponse = {};
  const consume = (line: string) => {
    const trimmed = line.trim();
    if (!trimmed) return;
    const chunk = JSON.parse(trimmed) as ChatResponse;
    if (chunk.error) throw new Error(chunk.error);
    if (chunk.message?.content) content += chunk.message.content;
    if (chunk.done) meta = chunk;
  };
  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true });
      let newline = buffer.indexOf("\n");
      while (newline >= 0) {
        consume(buffer.slice(0, newline));
        buffer = buffer.slice(newline + 1);
        newline = buffer.indexOf("\n");
      }
    }
    consume(buffer); // final line, which may lack a trailing newline
  } finally {
    reader.releaseLock();
  }

  if (!content) {
    throw new Error(`Ollama returned no content. ${meta.error || ""}`.trim());
  }

  const promptTokens = meta.prompt_eval_count ?? 0;
  const completionTokens = meta.eval_count ?? 0;
  // Ollama reports "length" when it hit num_predict. Fall back to the token
  // count in case a future/alternate provider omits done_reason.
  const truncated =
    meta.done_reason === "length" || completionTokens >= NUM_PREDICT;
  return {
    content,
    model: meta.model || model,
    promptTokens,
    completionTokens,
    totalTokens: promptTokens + completionTokens,
    truncated,
  };
}
